## Generate typed Nim accessors for a project's message catalogs.

import std/[algorithm, json, os, strutils, tables]
import ../mynim/i18n/message as messageFormat
import ./i18n_check

const generatedHeader = "## Code generated by `mygo generate`. DO NOT EDIT.\n"

type
  GeneratedArgument = object
    name, parameter, typ: string
    generic: bool

  GeneratedMessage = object
    key, accessor: string
    arguments: seq[GeneratedArgument]

proc nimStringLiteral(value: string): string =
  result = "\""
  for ch in value:
    case ch
    of '\\': result.add "\\\\"
    of '"': result.add "\\\""
    of '\n': result.add "\\n"
    of '\r': result.add "\\r"
    of '\t': result.add "\\t"
    else:
      if ord(ch) < 32:
        result.add "\\x" & toHex(ord(ch), 2)
      else:
        result.add ch
  result.add '"'

proc nimIdentifier(value: string): string =
  const keywords = [
    "addr", "and", "as", "asm", "bind", "block", "break", "case", "cast",
    "concept", "const", "continue", "converter", "defer", "discard", "distinct",
    "div", "do", "elif", "else", "end", "enum", "except", "export", "finally",
    "for", "from", "func", "if", "import", "in", "include", "interface", "is",
    "isnot", "iterator", "let", "macro", "method", "mixin", "mod", "nil", "not",
    "notin", "object", "of", "or", "out", "proc", "ptr", "raise", "ref", "return",
    "shl", "shr", "static", "template", "try", "tuple", "type", "using", "var",
    "when", "while", "xor", "yield"]
  if value.toLowerAscii() in keywords:
    "`" & value & "`"
  else:
    value

proc nimIdentifierKey(value: string): string =
  for ch in value:
    if ch != '_':
      result.add ch.toLowerAscii()

proc accessorName(key: string): string =
  var capitalize = true
  for ch in key:
    if ch == '_':
      capitalize = true
    elif capitalize:
      result.add ch.toUpperAscii()
      capitalize = false
    else:
      result.add ch
  if result.len > 0:
    result[0] = result[0].toLowerAscii()

proc declaredType(source: JsonNode; key, name, inferred: string): string =
  let metadataKey = "@" & key
  if source.kind == JObject and source.hasKey(metadataKey) and
      source[metadataKey].kind == JObject and
      source[metadataKey].hasKey("placeholders") and
      source[metadataKey]["placeholders"].kind == JObject and
      source[metadataKey]["placeholders"].hasKey(name):
    let placeholder = source[metadataKey]["placeholders"][name]
    if placeholder.kind == JObject and placeholder.hasKey("type") and
        placeholder["type"].kind == JString:
      return placeholder["type"].getStr()
  inferred

proc nimType(sourceType: string): tuple[typ: string, generic: bool] =
  case sourceType
  of "int": ("int", false)
  of "double": ("float", false)
  of "num": ("SomeNumber", true)
  of "DateTime": ("DateTime", false)
  of "Object": ("i18n.FormatArg", false)
  else: ("string", false)

proc inferredType(kind: string): string =
  case kind
  of "plural", "selectordinal", "number": "int"
  of "date", "time": "DateTime"
  else: "String"

proc messages(source: JsonNode): seq[GeneratedMessage] =
  var taken = initTable[string, string]()
  for reserved in ["Messages", "inLocale", "appCatalog", "withArgName"]:
    taken[nimIdentifierKey(reserved)] = ""

  for key, value in source:
    if key.startsWith("@") or value.kind != JString:
      continue
    let parsed = messageFormat.parseMessage(value.getStr())
    let name = accessorName(key)
    let nameKey = nimIdentifierKey(name)
    if taken.hasKey(nameKey):
      let previous = taken[nameKey]
      let detail = if previous.len == 0:
        "reserved generated name " & name
      else:
        "message keys " & previous & " and " & key &
          " collide as Nim accessor " & name
      raise newException(ValueError, "mygo i18n: " & detail)
    taken[nameKey] = key

    var item = GeneratedMessage(key: key, accessor: name)
    var argumentNames = initTable[string, string]()
    for arg in parsed.args():
      let parameterKey = nimIdentifierKey(arg.name)
      if argumentNames.hasKey(parameterKey):
        raise newException(ValueError,
          "mygo i18n: arguments " & argumentNames[parameterKey] & " and " &
          arg.name & " in " & key & " collide as Nim parameters")
      argumentNames[parameterKey] = arg.name
      let sourceType = declaredType(source, key, arg.name, inferredType(arg.kind))
      let mapped = nimType(sourceType)
      item.arguments.add GeneratedArgument(name: arg.name,
        parameter: arg.name, typ: mapped.typ, generic: mapped.generic)
    result.add item

proc addSignature(code: var string; item: GeneratedMessage;
    localized: bool) =
  var genericTypes: seq[string]
  var parameters: seq[string]
  var usedNames = initTable[string, bool]()
  for arg in item.arguments:
    usedNames[nimIdentifierKey(arg.parameter)] = true
  var receiver = ""
  if localized:
    receiver = "localizedMessages"
    var suffix = 0
    while usedNames.hasKey(nimIdentifierKey(receiver)):
      inc suffix
      receiver = "localizedMessages" & $suffix
    usedNames[nimIdentifierKey(receiver)] = true
    parameters.add receiver & ": Messages"
  var genericIndex = 0
  for arg in item.arguments:
    let parameter = nimIdentifier(arg.parameter)
    if arg.generic:
      var generic = "MygoNumber" & $genericIndex
      inc genericIndex
      while usedNames.hasKey(nimIdentifierKey(generic)):
        generic = "MygoNumber" & $genericIndex
        inc genericIndex
      usedNames[nimIdentifierKey(generic)] = true
      genericTypes.add generic & ": SomeNumber"
      parameters.add parameter & ": " & generic
    else:
      parameters.add parameter & ": " & arg.typ
  code.add "proc " & nimIdentifier(item.accessor) & "*"
  if genericTypes.len > 0:
    code.add "[" & genericTypes.join(", ") & "]"
  code.add "(" & parameters.join("; ") & "): string =\n  ## "
  if localized:
    code.add "Formats `" & item.key & "` in the explicitly selected locale.\n  "
  else:
    code.add "Formats `" & item.key & "` in the app's current locale.\n  "
  code.add "appCatalog.format("
  if localized:
    code.add receiver & ".localeTag, "
  code.add nimStringLiteral(item.key)
  for arg in item.arguments:
    code.add ", "
    if arg.typ == "i18n.FormatArg":
      code.add "withArgName(" & nimIdentifier(arg.parameter) & ", " &
        nimStringLiteral(arg.name) & ")"
    else:
      code.add "i18n.formatArg(" & nimStringLiteral(arg.name) & ", " &
        nimIdentifier(arg.parameter) & ")"
  code.add ")\n\n"

proc generateSource(sourceTag: string; tags, contents: seq[string];
    source: JsonNode): string =
  let generatedMessages = messages(source)
  var needsDateTime = false
  var needsFormatArg = false
  for item in generatedMessages:
    for arg in item.arguments:
      needsDateTime = needsDateTime or arg.typ == "DateTime"
      needsFormatArg = needsFormatArg or arg.typ == "i18n.FormatArg"
  result = generatedHeader & "\n"
  if needsDateTime:
    result.add "import std/times\n"
  result.add "import mynim/i18n as i18n\n\n" &
    "type Messages* = object ## Carries a locale for generated accessors.\n" &
    "  localeTag: string\n\n" &
    "proc inLocale*(locale: string): Messages =\n" &
    "  ## Selects a locale for the generated message accessors.\n" &
    "  Messages(localeTag: locale)\n\n"
  if needsFormatArg:
    result.add "proc withArgName(value: i18n.FormatArg; name: string): i18n.FormatArg =\n" &
      "  result = value\n  result.name = name\n\n"
  result.add("let appCatalog = block:\n" &
    "  let catalog = i18n.newCatalog(" & nimStringLiteral(sourceTag) & ", [\n")
  for index, tag in tags:
    result.add "    i18n.catalogFile(" & nimStringLiteral(tag) & ", " &
      nimStringLiteral(contents[index]) & ")"
    if index + 1 < tags.len:
      result.add ","
    result.add "\n"
  result.add "  ])\n  catalog.register()\n  catalog\n\n"

  for item in generatedMessages:
    addSignature(result, item, false)
    addSignature(result, item, true)

proc generateCatalogModule*(projectDir, sourcePath: string;
    config: JsonNode): string =
  ## Writes `catalog_gen.nim` beside the app entry point when catalogs exist.
  if config == nil or not config.hasKey("i18n") or config["i18n"].kind == JNull:
    return
  if runI18n(@["check", projectDir]) != 0:
    raise newException(ValueError, "i18n catalog check failed")

  let options = config["i18n"]
  let configuredSource = if options.hasKey("source"):
      options["source"].getStr("en")
    else:
      "en"
  let sourceTag = if configuredSource.len == 0: "en" else: configuredSource
  let configuredDir = if options.hasKey("dir"):
      options["dir"].getStr("locales")
    else:
      "locales"
  let relativeDir = if configuredDir.len == 0: "locales" else: configuredDir
  let catalogDir = projectDir / relativeDir
  var paths: seq[string]
  for kind, path in walkDir(catalogDir):
    if kind == pcFile and path.endsWith(".json") and
        not path.lastPathPart().startsWith("."):
      paths.add path
  paths.sort()

  var tags, contents: seq[string]
  var sourceDocument: JsonNode
  for path in paths:
    let tag = path.lastPathPart()[0 ..< path.lastPathPart().len - 5]
    tags.add tag
    let content = readFile(path)
    contents.add content
    if tag == sourceTag:
      sourceDocument = parseJson(content)
  if sourceDocument == nil:
    raise newException(ValueError,
      "i18n source catalog " & sourceTag & ".json is missing")

  result = sourcePath.parentDir() / "catalog_gen.nim"
  let generated = generateSource(sourceTag, tags, contents, sourceDocument)
  if fileExists(result):
    let existing = readFile(result)
    if not existing.startsWith(generatedHeader):
      raise newException(ValueError,
        "refusing to overwrite non-generated file " & result)
    if existing == generated:
      return
  writeFile(result, generated)
