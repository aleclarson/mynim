## tsgen.nim — writes the typed client for services and events bound
## through the JSON IPC API.

type
  TsMethod = object
    name: string
    params: seq[TypeScriptParam]
    resultType: string
    restArgs: bool

  TsService = object
    name: string
    methods: seq[TsMethod]

  TsEvent = object
    name: string
    tsType: string

const
  tsHeader = "// Code generated by `mynim generate`. DO NOT EDIT.\n"
  tsRuntimePackage = "mygo-runtime"
  tsReserved = [
    "arguments", "await", "break", "case", "catch", "class", "const",
    "continue", "debugger", "default", "delete", "do", "else", "enum",
    "eval", "export", "extends", "false", "finally", "for", "function",
    "if", "implements", "import", "in", "instanceof", "interface", "let",
    "new", "null", "package", "private", "protected", "public", "return",
    "static", "super", "switch", "this", "throw", "true", "try", "typeof",
    "var", "void", "while", "with", "yield"]

proc isTsIdentifier(s: string): bool =
  if s.len == 0:
    return false
  for i, c in s:
    let first = c == '_' or c == '$' or c in {'a'..'z', 'A'..'Z'}
    let later = first or c in {'0'..'9'}
    if (i == 0 and not first) or (i > 0 and not later):
      return false
  true

proc isTsBinding(s: string): bool =
  isTsIdentifier(s) and s notin tsReserved

proc tsProperty(s: string): string =
  if isTsIdentifier(s): s else: escapeJson(s)

proc tsSafeName(s, fallback: string): string =
  result = if s.len == 0: fallback else: s
  for i in 0 ..< result.len:
    let c = result[i]
    let valid = c == '_' or c == '$' or c in {'a'..'z', 'A'..'Z'} or
      (i > 0 and c in {'0'..'9'})
    if not valid:
      result[i] = '_'
  if result.len == 0 or result[0] in {'0'..'9'}:
    result = "_" & result
  if result in tsReserved:
    result.add '_'

proc tsCamel(s: string): string =
  result = s
  var upper = 0
  while upper < s.len and s[upper] in {'A'..'Z'}:
    inc upper
  let lowerCount =
    if upper == 1 or upper == s.len: upper
    elif upper > 1: upper - 1
    else: 0
  for i in 0 ..< lowerCount:
    result[i] = result[i].toLowerAscii()

proc tsEventKey(s: string): string =
  var capitalizeNext = false
  for i, c in s:
    if c in {'-', '_', ':', '.', ' ', '/'}:
      capitalizeNext = result.len > 0
    else:
      if capitalizeNext:
        result.add c.toUpperAscii()
        capitalizeNext = false
      elif i == 0:
        result.add c.toLowerAscii()
      else:
        result.add c
  if not isTsIdentifier(result):
    result = s

proc typeScriptSnapshot(): tuple[services: seq[TsService], events: seq[TsEvent]] =
  acquire(ipcMu)
  defer: release(ipcMu)
  for svc in ipcServices:
    if svc.internal:
      continue
    var service = TsService(name: svc.name)
    for mi in svc.methods:
      var meth = TsMethod(name: mi.name, resultType: "unknown")
      if mi.hasTsSignature:
        for param in mi.tsParams:
          meth.params.add param
        meth.resultType = mi.tsResult
      else:
        # The JSON handler erased its Nim signature. Keep that uncertainty
        # visible in the generated client while preserving known channels.
        for i, isChannel in mi.chans:
          meth.params.add TypeScriptParam(name: "arg" & $i,
            tsType: "unknown", channel: isChannel)
        meth.restArgs = true
      service.methods.add meth
    result.services.add service
  for e in ipcEvents:
    result.events.add TsEvent(name: e.name, tsType: e.tsType)

proc appendSection(source: var string; heading: string) =
  if source.len > 0 and source[^1] != '\n':
    source.add '\n'
  source.add "\n// ---- " & heading & " ----\n\n"

proc generateTypeScriptNative(): string =
  ## Renders the TypeScript client for registered user services and events.
  let snapshot = typeScriptSnapshot()
  result = tsHeader
  if snapshot.services.len == 0 and snapshot.events.len == 0:
    return

  var imports = @["call"]
  if snapshot.events.len > 0:
    imports.add "event"
  var hasChannels = false
  for service in snapshot.services:
    if not isTsBinding(service.name):
      raise newException(ValueError,
        "mynim: service name " & service.name.escape() &
        " cannot be exported as a TypeScript identifier")
    for meth in service.methods:
      for param in meth.params:
        hasChannels = hasChannels or param.channel
  if hasChannels:
    imports.add "type Channel"
  result.add "import { " & imports.join(", ") & " } from " &
    escapeJson(tsRuntimePackage) & ";\n"

  if snapshot.services.len > 0:
    result.appendSection("Services")
    for service in snapshot.services:
      var usedMethods = initHashSet[string]()
      result.add "export const " & service.name & " = {\n"
      for meth in service.methods:
        let key = tsCamel(meth.name)
        if usedMethods.contains(key):
          raise newException(ValueError,
            "mynim: methods of " & service.name.escape() &
            " collide in the generated TypeScript client at " & key.escape())
        usedMethods.incl key

        var usedParams = initHashSet[string]()
        var params: seq[string]
        var args: seq[string]
        for i, param in meth.params:
          let fallback = "arg" & $i
          var name = tsSafeName(param.name, fallback)
          while usedParams.contains(name):
            name.add '_'
          usedParams.incl name
          var typ = param.tsType
          if param.channel:
            typ = "Channel<" & typ & ">"
          params.add name & ": " & typ
          args.add name
        if meth.restArgs:
          params.add "...args: unknown[]"
          args.add "...args"

        let wireMethod = escapeJson(service.name & "." & meth.name)
        let callArgs = if args.len == 0: "" else: ", " & args.join(", ")
        result.add "  " & tsProperty(key) & "(" & params.join(", ") &
          "): Promise<" & meth.resultType & "> {\n" &
          "    return call(" & wireMethod & callArgs & ");\n" &
          "  },\n"
      result.add "} as const;\n"

  if snapshot.events.len > 0:
    var usedEvents = initHashSet[string]()
    result.appendSection("Events")
    result.add "export const events = {\n"
    for event in snapshot.events:
      let key = tsEventKey(event.name)
      if usedEvents.contains(key):
        raise newException(ValueError,
          "mynim: events collide in the generated TypeScript client at " &
          key.escape())
      usedEvents.incl key
      result.add "  " & tsProperty(key) & ": event<" & event.tsType & ">(" &
        escapeJson(event.name) & "),\n"
    result.add "} as const;\n"

when defined(emscripten):
  proc generateTypeScript*(): string =
    ## Browser builds do not generate a client.
    raise errUnsupported()
else:
  proc generateTypeScript*(): string = generateTypeScriptNative()

proc bindsAnything(): bool =
  acquire(ipcMu)
  defer: release(ipcMu)
  if ipcEvents.len > 0:
    return true
  for service in ipcServices:
    if not service.internal:
      return true

when defined(emscripten):
  proc writeTypeScript*(outPath: string) =
    ## Browser builds do not write generated clients.
    discard outPath
else:
  proc writeTypeScript*(outPath: string) =
    ## Writes the generated client, creating parents and leaving identical
    ## output untouched. Apps with no frontend IPC bindings write no file.
    if not bindsAnything():
      return
    let source = generateTypeScript() & "\n"
    if fileExists(outPath):
      try:
        if readFile(outPath) == source:
          return
      except IOError:
        discard
    let parent = parentDir(outPath)
    if parent.len > 0:
      createDir(parent)
    writeFile(outPath, source)
