proc testGenerateI18nCatalogModule() =
  let temporary = createTempDir("mynim-generate-i18n-", "")
  defer:
    if dirExists(temporary):
      removeDir(temporary)

  let project = temporary / "i18n-app"
  doAssert runInit(@["--mygo", getCurrentDir(), project]) == 0
  let configPath = project / "mygo.json"
  var config = parseFile(configPath)
  config["i18n"] = parseJson("""{"source":"en","dir":"locales"}""")
  writeFile(configPath, config.pretty & "\n")
  createDir(project / "locales")
  writeFile(project / "locales" / "en.json", """{
  "@@locale": "en",
  "greeting": "Hello, {name}!",
  "file_count": "{count, plural, one {# file} other {# files}}",
  "@file_count": {"placeholders": {"count": {"type": "num"}}},
  "amount": "{value, number}",
  "@amount": {"placeholders": {"value": {"type": "Object"}}},
  "meeting_date": "{when, date, short}",
  "collision_case": "{localizedMessages}: {mygoNumber0, plural, other {#}}",
  "@collision_case": {"placeholders": {"mygoNumber0": {"type": "num"}}}
}""")
  writeFile(project / "locales" / "de.json", """{
  "@@locale": "de",
  "greeting": "Grüße, {name}!",
  "file_count": "{count, plural, one {# Datei} other {# Dateien}}",
  "amount": "{value, number}",
  "meeting_date": "{when, date, short}",
  "collision_case": "lokalisiert {localizedMessages}: {mygoNumber0, plural, other {#}}"
}""")
  let mainPath = project / "src" / "main.nim"
  writeFile(mainPath, """import mynim
import std/times
import mynim/i18n as i18n
import catalog_gen

doAssert catalog_gen.inLocale("de").greeting("Ada") == "Grüße, Ada!"
doAssert "de" in i18n.languages()
doAssert catalog_gen.inLocale("de").fileCount(2) == "2 Dateien"
doAssert catalog_gen.inLocale("de").fileCount(2.5) == "2,5 Dateien"
doAssert catalog_gen.inLocale("de").collisionCase("passt", 3) == "lokalisiert passt: 3"
doAssert catalog_gen.inLocale("en").amount(i18n.formatArg("other", 7)) == "7"
doAssert catalog_gen.inLocale("en").meetingDate(dateTime(2025, mJan, 2)).len > 0
app.run()
""")

  doAssert runGenerate(@[project]) == 0
  let generated = project / "src" / "catalog_gen.nim"
  doAssert fileExists(generated)
  doAssert readFile(generated).startsWith(
    "## Code generated by `mygo generate`. DO NOT EDIT.")

